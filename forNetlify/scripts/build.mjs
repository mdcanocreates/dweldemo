/**
 * Build production web/ with Netlify demo flag, then emit dist/ + _redirects
 * that proxy /v1 and /health to DWEL_API_ORIGIN (same-origin for the browser).
 *
 * Required at Netlify build time:
 *   DWEL_API_ORIGIN=https://<dwel-api-host>   (no trailing slash)
 *
 * Secrets are never copied — only the public API origin for proxy rewrites.
 */
import { spawnSync } from 'node:child_process';
import {
  cpSync,
  existsSync,
  mkdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const forNetlifyRoot = resolve(here, '..');
const webRoot = resolve(forNetlifyRoot, '../web');
const outDist = join(forNetlifyRoot, 'dist');

const apiOrigin = (process.env.DWEL_API_ORIGIN ?? process.env.VITE_API_PROXY_TARGET ?? '')
  .trim()
  .replace(/\/$/, '');

if (!apiOrigin) {
  console.error(
    '[forNetlify] Missing DWEL_API_ORIGIN (e.g. https://api.example.com). Refusing to build a demo that cannot authenticate.',
  );
  process.exit(1);
}

if (!/^https?:\/\//i.test(apiOrigin)) {
  console.error(`[forNetlify] DWEL_API_ORIGIN must be an absolute http(s) URL, got: ${apiOrigin}`);
  process.exit(1);
}

if (!existsSync(join(webRoot, 'package.json'))) {
  console.error(`[forNetlify] Expected web app at ${webRoot}`);
  process.exit(1);
}

console.log(`[forNetlify] Building web from ${webRoot}`);
console.log(`[forNetlify] API proxy origin: ${apiOrigin}`);

const install = spawnSync('npm', ['ci'], {
  cwd: webRoot,
  stdio: 'inherit',
  shell: process.platform === 'win32',
  env: process.env,
});
if (install.status !== 0) {
  // Fallback when lockfile drift blocks ci
  const installLegacy = spawnSync('npm', ['install'], {
    cwd: webRoot,
    stdio: 'inherit',
    shell: process.platform === 'win32',
    env: process.env,
  });
  if (installLegacy.status !== 0) process.exit(installLegacy.status ?? 1);
}

const build = spawnSync('npm', ['run', 'build'], {
  cwd: webRoot,
  stdio: 'inherit',
  shell: process.platform === 'win32',
  env: {
    ...process.env,
    VITE_DWEL_NETLIFY_DEMO: 'true',
    VITE_APP_ENV: process.env.VITE_APP_ENV ?? 'demo',
  },
});
if (build.status !== 0) process.exit(build.status ?? 1);

const webDist = join(webRoot, 'dist');
if (!existsSync(webDist)) {
  console.error('[forNetlify] web build did not produce dist/');
  process.exit(1);
}

rmSync(outDist, { recursive: true, force: true });
mkdirSync(outDist, { recursive: true });
cpSync(webDist, outDist, { recursive: true });

const redirects = `# Generated by forNetlify/scripts/build.mjs — do not hand-edit
# Same-origin proxy so the production client can keep relative /v1/* fetches.
/v1/*  ${apiOrigin}/v1/:splat  200
/health  ${apiOrigin}/health  200
/health/*  ${apiOrigin}/health/:splat  200

# SPA fallback (hash router still needs index.html on cold loads)
/*    /index.html   200
`;

writeFileSync(join(outDist, '_redirects'), redirects, 'utf8');

const meta = {
  built_at: new Date().toISOString(),
  api_origin: apiOrigin,
  vite_dwel_netlify_demo: true,
  note: 'No secrets embedded. Session cookies rely on Netlify 200 proxy forwarding Set-Cookie.',
};
writeFileSync(join(outDist, 'demo-build.json'), JSON.stringify(meta, null, 2), 'utf8');

console.log(`[forNetlify] Published ${outDist}`);
console.log('[forNetlify] Wrote _redirects proxy for /v1/* and /health');
