/**
 * Build standalone Netlify demo from production web/.
 *
 * Sets VITE_DWEL_NETLIFY_DEMO=true so the app uses local demo access +
 * in-memory fixtures (no magic link, no AWS API, no DWEL_API_ORIGIN).
 *
 * Secrets are never copied. Outbound /v1 calls are blocked at runtime in demo builds.
 */
import { spawnSync } from 'node:child_process';
import {
  cpSync,
  existsSync,
  mkdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const forNetlifyRoot = resolve(here, '..');
const webRoot = resolve(forNetlifyRoot, '../web');
const outDist = join(forNetlifyRoot, 'dist');

if (!existsSync(join(webRoot, 'package.json'))) {
  console.error(`[forNetlify] Expected web app at ${webRoot}`);
  process.exit(1);
}

console.log(`[forNetlify] Building standalone demo from ${webRoot}`);
console.log('[forNetlify] Mode: offline fixtures (no DWEL_API_ORIGIN required)');

const install = spawnSync('npm', ['ci'], {
  cwd: webRoot,
  stdio: 'inherit',
  shell: process.platform === 'win32',
  env: process.env,
});
if (install.status !== 0) {
  const installLegacy = spawnSync('npm', ['install'], {
    cwd: webRoot,
    stdio: 'inherit',
    shell: process.platform === 'win32',
    env: process.env,
  });
  if (installLegacy.status !== 0) process.exit(installLegacy.status ?? 1);
}

const build = spawnSync('npm', ['run', 'build'], {
  cwd: webRoot,
  stdio: 'inherit',
  shell: process.platform === 'win32',
  env: {
    ...process.env,
    VITE_DWEL_NETLIFY_DEMO: 'true',
    VITE_APP_ENV: process.env.VITE_APP_ENV ?? 'demo',
  },
});
if (build.status !== 0) process.exit(build.status ?? 1);

const webDist = join(webRoot, 'dist');
if (!existsSync(webDist)) {
  console.error('[forNetlify] web build did not produce dist/');
  process.exit(1);
}

rmSync(outDist, { recursive: true, force: true });
mkdirSync(outDist, { recursive: true });
cpSync(webDist, outDist, { recursive: true });

// SPA-only — no /v1 proxy (demo must not reach production APIs).
const redirects = `# Generated by forNetlify/scripts/build.mjs — standalone demo
# No API proxy: all /v1 traffic is handled in-browser by demo adapters.

# SPA fallback (hash router still needs index.html on cold loads)
/*    /index.html   200
`;

writeFileSync(join(outDist, '_redirects'), redirects, 'utf8');

const meta = {
  built_at: new Date().toISOString(),
  mode: 'standalone_demo',
  api_origin: null,
  vite_dwel_netlify_demo: true,
  note: 'No secrets. No AWS API. Local demo email gate + in-memory fixtures only.',
};
writeFileSync(join(outDist, 'demo-build.json'), JSON.stringify(meta, null, 2), 'utf8');

console.log(`[forNetlify] Published ${outDist}`);
console.log('[forNetlify] Standalone demo — no /v1 proxy written');
